  function ruleFor(sheet, layer, key, tags) {
    if (sheet.understands.indexOf(layer) < 0) return { action: 'not-understood', reason: sheet.name + ' does not read the ' + layer + ' layer; kept untouched in the passport' };
    var rules = sheet.rules || [];
    for (var i = 0; i < rules.length; i++) {
      var r = rules[i], m = r.match || {};
      if (m.layer != null && m.layer !== layer) continue;
      if (m.key != null && !glob(m.key, key)) continue;
      if (Array.isArray(m.tags) && !m.tags.some(function (t) { return tags.indexOf(t) >= 0; })) continue;
      return { action: r.action, cap: r.cap, reason: r.reason || '', ruleIndex: i };
    }
    return { action: sheet.defaultAction || 'allow', reason: sheet.defaultReason || '' };
  }

